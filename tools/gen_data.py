import csv, io, os, urllib.request

BUILD = "1.60.1.70938"
LOCALES = ["enUS", "esES", "esMX", "frFR", "deDE", "itIT",
           "ptBR", "ruRU", "koKR", "zhCN", "zhTW"]
KEEP_TYPES = {1, 2, 3, 6}  # World, Continent, Zone, Battleground (Type 6 in this build; no Cosmic/Micro/Dungeon present)

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "MapNameTranslator", "Data.lua")

def fetch(locale):
    url = "https://wago.tools/db2/UiMap/csv?build=%s&locale=%s" % (BUILD, locale)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read().decode("utf-8-sig")

def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

def main():
    data = {}
    for loc in LOCALES:
        reader = csv.DictReader(io.StringIO(fetch(loc)))
        for row in reader:
            try:
                map_id = int(row["ID"])
                mtype = int(row["Type"])
            except (KeyError, ValueError):
                continue
            if mtype not in KEEP_TYPES:
                continue
            data.setdefault(map_id, {})[loc] = (row.get("Name_lang") or "").strip()
    lines = [
        "-- Generated by tools/gen_data.py from wago.tools UiMap (build %s). Do not edit." % BUILD,
        "local _, ns = ...",
        "ns.Data = {",
    ]
    for map_id in sorted(data):
        entry = ", ".join('%s = %s' % (loc, quote(data[map_id][loc])) for loc in LOCALES)
        lines.append("\t[%d] = { %s }," % (map_id, entry))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("Wrote %d maps to %s" % (len(data), OUT))

main()
